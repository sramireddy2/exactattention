"""How many int8 slices do tensor-core scores need? Measured on real activations.

For sampled (layer, head, position) rows of the captured model, compute q.k for every
prefix key through the int8-slice path (slices.py) under several (Sq, Sk, pair-set)
configurations. Count how often the rigorous error bound certifies t = RN32(alpha*s), and
check every certified t against the exact score.

    python scripts/slice_study.py --data <captures> --out results/slice_study_qwen3-0.6b.md
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import time

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))
sys.path.insert(0, os.path.dirname(__file__))

from exactattn.formats import FP32, decode_fp32, dyadic_to_float, round_dyadic  # noqa: E402
from exactattn.reference import decode_bf16_array, exact_dot  # noqa: E402
from exactattn.slices import slice_rows, sliced_scores, triangle_pairs  # noqa: E402
from validate_model import alpha_for  # noqa: E402

CONFIGS = [
    ("3x3 all", 3, 3, None),
    ("3x4 all", 3, 4, None),
    ("4x4 tri4", 4, 4, 4),
    ("4x4 tri5", 4, 4, 5),
    ("4x4 all", 4, 4, None),
    ("5x5 tri5", 5, 5, 5),
    ("5x5 all", 5, 5, None),
    ("6x6 all", 6, 6, None),
]


def certify(am, ae, acc, err, unit):
    """Return (certified mask, t values) using exact rounding of both interval ends."""
    ok = np.zeros(len(acc), bool)
    t = np.zeros(len(acc))
    for j, (a, e, u) in enumerate(zip(acc.tolist(), err.tolist(), np.asarray(unit).tolist())):
        lo = round_dyadic(am * (a - e), ae + u, FP32)
        hi = round_dyadic(am * (a + e), ae + u, FP32)
        tl, th = dyadic_to_float(*lo), dyadic_to_float(*hi)
        ok[j] = tl == th
        t[j] = tl
    return ok, t


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--rows", type=int, default=40)
    args = ap.parse_args()
    meta = json.load(open(os.path.join(args.data, "meta.json")))
    rng = np.random.default_rng(1)
    L = meta["tokens"]
    picks = [(int(rng.integers(0, 28)), int(rng.integers(0, 16)), int(rng.integers(L // 4, L))) for _ in range(args.rows)]
    stats = {name: {"ok": 0, "n": 0, "mma": 0, "wrong": 0} for name, *_ in CONFIGS}
    t0 = time.time()
    for li, h, pos in picks:
        lm = meta["layers"][str(li)]
        kv = h // lm["groups"]
        Q = np.load(os.path.join(args.data, f"layer{li:02d}_q.npy"), mmap_mode="r")
        K = np.load(os.path.join(args.data, f"layer{li:02d}_k.npy"), mmap_mode="r")
        q = np.array(Q[h, pos])[None, :]
        k = np.array(K[kv, : pos + 1])
        alpha = alpha_for(lm["scaling"])
        am, ae = decode_fp32(np.float32(alpha))
        # exact logits for checking
        qm, qe = decode_bf16_array(q[0])
        km, ke = decode_bf16_array(k)
        t_exact = []
        for j in range(k.shape[0]):
            sm, se = exact_dot(qm, qe, km[j], ke[j])
            t_exact.append(0.0 if sm == 0 else dyadic_to_float(*round_dyadic(am * sm, ae + se, FP32)))
        t_exact = np.array(t_exact)
        for name, Sq, Sk, depth in CONFIGS:
            qX, qlsb, ql1, qlost = slice_rows(q, Sq)
            kX, klsb, kl1, klost = slice_rows(k, Sk)
            pairs = None if depth is None else triangle_pairs(Sq, Sk, depth)
            acc, err, n_mma = sliced_scores(qX[:, 0, :], int(qlsb[0]), ql1[0], qlost[0], kX, klsb, kl1, klost, pairs)
            ok, t = certify(am, ae, acc, err, int(qlsb[0]) + klsb)
            st = stats[name]
            st["ok"] += int(ok.sum())
            st["n"] += len(ok)
            st["mma"] = n_mma
            st["wrong"] += int((ok & (t != t_exact)).sum())
        print(f"row {li}/{h}/{pos} done ({time.time() - t0:.0f}s)", flush=True)

    lines = [
        f"# int8-slice tensor-core scores: certification on real activations ({meta['model']})",
        "",
        f"{len(picks)} random query rows (layers × heads × positions in the last 3/4 of {L} tokens),",
        "every causal prefix key. q and each K row are split into signed 7-bit int8 digits under",
        "their own block exponent. `tri` keeps only the slice pairs within that many digits of the",
        "top pair, and counts the dropped pairs' worst case in the error bound. Generated by",
        "`scripts/slice_study.py`.",
        "",
        "| config | int8 dot products per score (MMA k-steps) | scores certified | uncertified rate | certified but wrong (must be 0) |",
        "|---|---|---|---|---|",
    ]
    for name, *_ in CONFIGS:
        s = stats[name]
        lines.append(f"| {name} | {s['mma']} | {s['ok']:,} / {s['n']:,} | {1 - s['ok'] / s['n']:.2e} | {s['wrong']} |")
    lines += ["", "For reference, a bf16 score costs one bf16 MMA k-step. On A100 and H100, int8 tensor-core",
              "throughput is twice bf16, so `n` int8 dot products cost about n/2 bf16 MMAs."]
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
