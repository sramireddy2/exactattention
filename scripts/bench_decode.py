"""Decode/verify-shape timing on one GPU: ExactAttention (Triton) vs torch SDPA.

The shape is one KV head with R query rows sharing it (GQA group × draft tokens) and n cached
keys, d = d_v = 128. It times the device-level launch with CUDA events, excluding host copies
and K slicing (done once at cache write). It reports ms, effective K+V bandwidth in GB/s, and
the slowdown relative to SDPA. This measures v0 and v1 honestly; P·V is still int64 CUDA-core
work.

    python scripts/bench_decode.py --out results/bench_decode_<gpu>.md
"""

from __future__ import annotations

import argparse
import os
import sys

import numpy as np
import torch
import torch.nn.functional as F

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

from exactattn import default_alpha, float_to_bf16_bits  # noqa: E402
from exactattn.triton_kernels import launch, tc_slices  # noqa: E402


def timeit(fn, iters=20, warmup=3):
    for _ in range(warmup):
        fn()
    torch.cuda.synchronize()
    s, e = torch.cuda.Event(enable_timing=True), torch.cuda.Event(enable_timing=True)
    s.record()
    for _ in range(iters):
        fn()
    e.record()
    torch.cuda.synchronize()
    return s.elapsed_time(e) / iters


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--rows", default="16")
    ap.add_argument("--keys", default="1024,4096,16384")
    args = ap.parse_args()
    dev = torch.device("cuda")
    name = torch.cuda.get_device_name(0)
    rng = np.random.default_rng(0)
    d = 128
    alpha = default_alpha(d)
    lines = [f"# Decode-shape timing on {name}", "",
             "One KV head, R queries sharing it, n keys, d = d_v = 128, bf16 out. CUDA events, mean of",
             "20 runs. `GB/s` = (K + V bytes) / time. Generated by `scripts/bench_decode.py`.", "",
             "| R | n | SDPA ms | exact (windowed int64) ms | exact (int8 TC scores) ms | TC GB/s | TC / SDPA | uncertified rows |",
             "|---|---|---|---|---|---|---|---|"]
    for R in [int(x) for x in args.rows.split(",")]:
        for n in [int(x) for x in args.keys.split(",")]:
            q = float_to_bf16_bits(rng.standard_normal((R, d)))
            k = float_to_bf16_bits(rng.standard_normal((n, d)))
            v = float_to_bf16_bits(rng.standard_normal((n, d)))
            t16 = lambda x: torch.from_numpy(x.view(np.int16)).to(dev)  # noqa: E731
            Qt, Kt, Vt = t16(q), t16(k), t16(v)
            KL = torch.full((R,), n, dtype=torch.int32, device=dev)
            splits = max(1, min(64, n // 256))
            qb, kb, vb = (x.view(torch.bfloat16)[None, None] for x in (Qt, Kt, Vt))
            t_sdpa = timeit(lambda: F.scaled_dot_product_attention(qb, kb, vb))
            t_win = timeit(lambda: launch(Qt, Kt, Vt, KL, n, alpha, splits=splits), iters=5, warmup=1)
            q_tc, k_tc = tc_slices(q, 3, dev), tc_slices(k, 4, dev)
            t_tc = timeit(lambda: launch(Qt, Kt, Vt, KL, n, alpha, splits=splits, q_tc=q_tc, k_tc=k_tc),
                          iters=5, warmup=1)
            _, FL, OF = launch(Qt, Kt, Vt, KL, n, alpha, splits=splits, q_tc=q_tc, k_tc=k_tc)
            unc = int(((FL.amax(dim=(0, 2)) > 0) | (OF.amax(dim=1) > 0)).sum())
            gbs = 2 * n * d * 2 / (t_tc * 1e-3) / 1e9
            lines.append(f"| {R} | {n} | {t_sdpa:.3f} | {t_win:.2f} | {t_tc:.2f} | {gbs:.1f} | {t_tc / t_sdpa:.0f}x | {unc} |")
            print(lines[-1], flush=True)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
